from machine import Pin, ADC
from neopixel import NeoPixel
import time

# ==========================================
# MQ-2 가스 센서
# ==========================================
mq2 = ADC(26)  # GP26 (ADC0)

# ==========================================
# WS2813 네오픽셀
# ==========================================
TIMING = (280, 515, 515, 745)
led = NeoPixel(Pin(16), 10, timing=TIMING)

# ==========================================
# 기준값
# ==========================================
SAFE = 780
WARNING = 800
DANGER = 830


# ==========================================
# LED 표시 함수
# ==========================================
def show_led(count, color):

    # 모든 LED 끄기
    for i in range(10):
        led[i] = (0, 0, 0)

    # count만큼 LED 켜기
    for i in range(count):
        led[i] = color

    led.write()


# ==========================================
# 프로그램 시작
# ==========================================
print("MQ-2 가스 감지 시스템 시작")
print("기준값: 780 / 800 / 830")


# ==========================================
# 메인 반복
# ==========================================
while True:

    # MQ-2 센서값 읽기
    sensor_value = mq2.read_u16()

    # --------------------------------------
    # 780 미만
    # 안전
    # --------------------------------------
    if sensor_value < SAFE:

        # 1~3개
        level = 1 + int(
            sensor_value / SAFE * 2
        )

        if level > 3:
            level = 3

        color = (0, 40, 0)
        status = "안전"


    # --------------------------------------
    # 780 ~ 799
    # 주의로 올라가는 구간
    # --------------------------------------
    elif sensor_value < WARNING:

        # 3~5개
        level = 3 + int(
            (sensor_value - SAFE) /
            (WARNING - SAFE) * 2
        )

        if level > 5:
            level = 5

        color = (40, 30, 0)
        status = "주의"


    # --------------------------------------
    # 800 ~ 829
    # 주의
    # --------------------------------------
    elif sensor_value < DANGER:

        # 6~8개
        level = 6 + int(
            (sensor_value - WARNING) /
            (DANGER - WARNING) * 2
        )

        if level > 8:
            level = 8

        color = (40, 20, 0)
        status = "주의"


    # --------------------------------------
    # 830 이상
    # 위험
    # --------------------------------------
    else:

        # 10개 모두 켜기
        level = 10

        color = (50, 0, 0)
        status = "위험"


    # LED 표시
    show_led(level, color)


    # --------------------------------------
    # 센서값 출력
    # --------------------------------------
    print(
        "MQ-2:",
        sensor_value,
        "| 상태:",
        status,
        "| LED:",
        level,
        "/ 10"
    )

    time.sleep(0.2)
